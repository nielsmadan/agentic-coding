#!/usr/bin/env python3
"""Legacy driver for the global permission files.

The eight global permission files are now generated by `loadout sync` from
permissions/permissions.toml — see loadout.toml's [permissions.*] targets.
This script no longer emits anything; it is kept so the `--check` entry point
referenced by lefthook.yml stays valid.

Project-local permission management still lives in permissions/manage.py.
"""

from __future__ import annotations

import difflib
import os
import sys
import tempfile
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "permissions" / "permissions.toml"


# --------------------------------------------------------------------------
# driver
# --------------------------------------------------------------------------

def render_all():
    """The eight global permission files are generated by `loadout sync`.

    See loadout.toml's [permissions.*] targets. Project-local permission
    management still lives in permissions/manage.py.
    """
    return {}


def atomic_write(path, content):
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".sync-")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(content)
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.unlink(tmp)
        raise


def write_all():
    files = render_all()
    originals = {
        path: path.read_text() if path.exists() else None
        for path in files
    }
    try:
        for path, content in files.items():
            atomic_write(path, content)
            print(f"wrote {path.relative_to(REPO_ROOT)}")
    except BaseException:
        for path, content in originals.items():
            if content is None:
                if path.exists():
                    path.unlink()
            else:
                atomic_write(path, content)
        raise


def check_all():
    drift = []
    for path, expected in render_all().items():
        actual = path.read_text() if path.exists() else ""
        if actual != expected:
            drift.append((path, actual, expected))
    if not drift:
        print("permission files are up to date")
        return 0
    for path, actual, expected in drift:
        rel = path.relative_to(REPO_ROOT)
        print(f"DRIFT: {rel}", file=sys.stderr)
        sys.stderr.writelines(
            difflib.unified_diff(
                actual.splitlines(keepends=True),
                expected.splitlines(keepends=True),
                fromfile=f"{rel} (on disk)",
                tofile=f"{rel} (expected)",
            )
        )
    print(
        f"\n{len(drift)} permission file(s) out of sync — "
        "run permissions/sync.py to regenerate.",
        file=sys.stderr,
    )
    return 1


def main(argv):
    if not SOURCE.exists():
        print(f"source not found: {SOURCE}", file=sys.stderr)
        return 1
    if argv == ["--check"]:
        return check_all()
    if argv:
        print(f"usage: {Path(__file__).name} [--check]", file=sys.stderr)
        return 2
    write_all()
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
